# ---------------------------------------------------------------------------
# 市场板块（互斥分类，用于按市场筛选）
#   sh=上证主板  sz=深证主板  bj=北交所  kcb=科创板  cyb=创业板
# ---------------------------------------------------------------------------
MARKETS = {
    "sh":  {"zh": "上证", "prefixes": ("600", "601", "603", "605")},
    "sz":  {"zh": "深证", "prefixes": ("000", "001", "002", "003")},
    "bj":  {"zh": "北证", "prefixes": ("43", "83", "87", "88", "92")},
    "kcb": {"zh": "科创", "prefixes": ("688", "689")},
    "cyb": {"zh": "创业", "prefixes": ("300", "301")},
}


def classify_market(code: str) -> str:
    """按 6 位代码判定所属市场板块，返回 sh/sz/bj/kcb/cyb/other。"""
    c = str(code).zfill(6)
    for key, cfg in MARKETS.items():
        if c.startswith(cfg["prefixes"]):
            return key
    return "other"


